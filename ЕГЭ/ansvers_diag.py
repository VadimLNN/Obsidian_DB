# №6. Комбинаторика, открытый вариант-2025, задача 8
# ------------------------------------------------------------
def task06():
    count = 0
    for n in range(1000, 10_000):
        digits = [int(ch) for ch in str(n)]
        # Длина 4 автоматически исключает ведущий нуль.
        if len(set(digits)) != 4:
            continue  # все четыре цифры должны быть различными
        # Остатки при делении на 2 соседних цифр должны отличаться.
        if all(digits[i] % 2 != digits[i + 1] % 2 for i in range(3)):
            count += 1
    return count


