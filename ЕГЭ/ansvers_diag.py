# №12. Кодирование, открытый вариант-2025, задача 11
# ------------------------------------------------------------
def task12():
    limit = 77 * 1024 * 1024
    count = 703_569
    length = 246
    # Максимальная мощность алфавита при b битах на символ — 2^b.
    # На каждый номер отводится целое число байт (округление вверх).
    suitable_bits = [bits for bits in range(1, 100)
                     if count * ((length * bits + 7) // 8) <= limit]
    return 2 ** max(suitable_bits)


