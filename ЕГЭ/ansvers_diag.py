# №15. 36-ричная запись, открытый вариант-2026, задача 14
# ------------------------------------------------------------
def task15():
    n = (5 * 1296**2021 - 4 * 216**2022
         + 3 * 36**2023 - 2 * 6**2024 - 2025)
    # Переводим в 36-ричную систему. Цифры храним как ЧИСЛА 0..35,
    # а не символы 0..9,A..Z. Тогда число чётных цифр легко найти.
    digits = number_to_base(n, 36)
    return sum(digit % 2 == 0 for digit in digits)


