from itertools import product


def number_to_base(n: int, base: int) -> list[int]:
    """Цифры n в системе base, от старшей к младшей (без ведущих нулей)."""
    assert n >= 0 and base >= 2
    if n == 0:
        return [0]
    digits = []
    while n:
        digits.append(n % base)
        n //= base
    return digits[::-1]


def prefix_free(words: list[str]) -> bool:
    """Проверка условия Фано: никакой код не может быть префиксом другого."""
    if len(words) != len(set(words)):
        return False
    return all(
        not b.startswith(a)
        for i, a in enumerate(words)
        for j, b in enumerate(words)
        if i != j
    )


