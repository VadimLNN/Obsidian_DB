# №13. 19-ричная система, демоверсия-2025, задача 14 (вариант 1)
# ------------------------------------------------------------
def task13():
    # Переводим цифру x в десятичное значение при основании 19.
    # Заменяем латинскую 'x' её числом, не строкой '10' и т.д.
    def decode(text: str, base: int, unknown: int) -> int:
        value = 0
        for ch in text:
            if ch == 'x':
                digit = unknown
            else:
                digit = int(ch)
            value = value * base + digit
        return value

    for x in range(18, -1, -1):  # наибольшая цифра — первая подходящая
        total = decode('98897x21', 19, x) + decode('2x923', 19, x)
        if total % 18 == 0:
            return total // 18
    raise AssertionError('Нет подходящей цифры x')


# ------------------------------------------------------------
# №14. Семеричная запись, открытый вариант-2025, задача 14
# ------------------------------------------------------------
def task14():
    # x — положительное целое, x<=2300. Нужен МАКСИМУМ x.
    # Поэтому проверяем значения сразу в порядке убывания.
    for x in range(2300, 0, -1):
        n = 7**350 + 7**150 - x
        if number_to_base(n, 7).count(0) == 200:
            return x
    raise AssertionError('Решение не найдено')


