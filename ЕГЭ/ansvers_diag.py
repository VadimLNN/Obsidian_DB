# №11. Комбинаторика, открытый вариант-2026, задача 8
# ------------------------------------------------------------
def task11():
    # ВАЖНО: символы русского алфавита и их алфавитный порядок.
    alphabet = 'АЕЛПРЬ'  # А, Е, Л, П, Р, Ь
    for position, letters in enumerate(product(alphabet, repeat=6), 1):
        word = ''.join(letters)
        if (position % 2 == 1              # нечётный номер
                and word[0] not in 'АЛ'   # первая буква не А и не Л
                and word.count('П') >= 2):
            return position
    raise AssertionError('Слово не найдено')


