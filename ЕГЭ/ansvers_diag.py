# №9. Кодирование, демоверсия-2025, задача 11
# ------------------------------------------------------------
def task09():
    alphabet = 10 + 52 + 963  # 1025 различных символов
    bits_per_symbol = (alphabet - 1).bit_length()  # 11 бит
    available_bytes = 693 * 1024
    # В памяти хранится 2000 номеров одинаковой длины.
    # Байты на один номер округляются вверх, длину ищем снизу вверх.
    max_len = 0
    length = 1
    while True:
        bytes_per_number = (length * bits_per_symbol + 7) // 8
        if 2000 * bytes_per_number > available_bytes:
            break
        max_len = length
        length += 1
    return max_len


