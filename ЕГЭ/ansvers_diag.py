def task03():
    alphabet = 17 + 4080  # 4097 символов
    # 2^12=4096 не хватает; 2^13=8192 достаточно.
    bits_per_symbol = (alphabet - 1).bit_length()  # 13
    bytes_per_id = (257 * bits_per_symbol + 7) // 8  # 418 байт
    total_bytes = bytes_per_id * 8_388_608
    return total_bytes // (1024 * 1024)  # 3344 Мбайт


# ------------------------------------------------------------
# №4. Фано, открытый вариант-2026, задача 4
# ------------------------------------------------------------
def task04():
    known = ['00', '010', '011', '1011', '1001', '1100', '1010', '1101', '111']
    # Сначала перебираем короткие слова. Для одной длины — по числовому
    # значению по возрастанию. Поэтому первый корректный код оптимален.
    for length in range(1, 12):
        for number in range(2 ** length):
            candidate = format(number, f'0{length}b')
            if prefix_free(known + [candidate]):
                return candidate
    raise AssertionError('Код не найден')


# ------------------------------------------------------------
# №5. Фано, открытый вариант-2025, задача 4
# ------------------------------------------------------------
def task05():
    known = ['00', '1000', '010', '1001', '011', '111']
    # Перебор всех пар новых двоичных слов длиной <=6. Ищем минимальную
    # сумму длин, причём коды Ж и З должны различаться и сохранять Фано.
    candidates = [format(x, f'0{length}b')
                  for length in range(1, 7)
                  for x in range(2 ** length)]
    best = min(
        (len(a) + len(b), a, b)
        for a in candidates
        for b in candidates
        if prefix_free(known + [a, b])
    )
    # Например, подходит 101 и 110: оба длины 3, сумма 6.
    return best[0]


